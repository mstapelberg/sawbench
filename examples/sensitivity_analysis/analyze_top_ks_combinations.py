def load_ks_cache(cache_file: str) -> List[Dict[str, Any]]:
    """Load KS cache from JSON file and return as list of entries."""
    if not os.path.exists(cache_file):
        raise FileNotFoundError(f"Cache file not found: {cache_file}")
    
    # Load JSON cache (new format: hash -> {KS, K, D, G, C11, C12, C44})
    try:
        with open(cache_file, 'r') as f:
            cache_dict = json.load(f)
        
        # Convert to list of entries
        entries = list(cache_dict.values())
        print(f"Loaded {len(entries)} entries from {cache_file} (JSON format)")
        return entries
        
    except (json.JSONDecodeError, UnicodeDecodeError):
        # Try old pickle format for backward compatibility
        print(f"Warning: {cache_file} is not in new JSON format")
        print("Please regenerate cache with updated ternary_saw_frequency.py")
        raise RuntimeError("Old cache format not supported. Please regenerate cache.")


