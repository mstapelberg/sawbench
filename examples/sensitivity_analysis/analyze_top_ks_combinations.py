"""Analyze Top KS Metric Combinations from Cache.

This script analyzes the best-performing elastic constant combinations from a 
KS cache file generated by ternary_saw_frequency.py in KS mode. It:

1. Loads a KS metric cache (pickle file)
2. Identifies the top N combinations with the LOWEST KS metrics (best agreement)
3. Re-computes SAW frequency distributions for those combinations using EBSD data
4. Plots cumulative distribution functions (CDFs) comparing predictions to experiment
5. Plots frequency histograms for visual comparison

The output includes two figures:
- Combined figure with histogram (bottom) and CDF (top) sharing x-axis
- Clear color-coding and numbering for each K/D/G combination
- Experimental data shown for reference

Usage:
    python analyze_top_ks_combinations.py \\
        --cache_file results/ternary_ks_cache.pkl \\
        --ebsd_path ../data/TGS-Mapping/V-1_2Ti_EBSD \\
        --experimental_h5 ../data/TGS-Mapping/fftData.h5 \\
        --top_n 5 \\
        --num_workers 8 \\
        --output_prefix results/top_ks_analysis

"""

