    parser.add_argument("--num_workers", type=int, default=8,
                       help="Number of parallel workers (default: 8)")
    parser.add_argument("--output_prefix", type=str, default="results/top_ks_analysis",
                       help="Output file prefix (default: results/top_ks_analysis)")
    
    # Parameters from original run (needed to reconstruct)
    parser.add_argument("--density", type=float, default=6110.0,
                       help="Density in kg/m^3 (default: 6110.0)")
    parser.add_argument("--wavelength_um", type=float, default=8.8,
                       help="Wavelength in micrometers (default: 8.8)")
    parser.add_argument("--deg", type=float, default=135.0,
                       help="Propagation angle in degrees (default: 135.0)")
    parser.add_argument("--sampling", type=int, default=400,
                       help="SAW sampling parameter (default: 400)")
    parser.add_argument("--exp_min_mhz", type=float, default=200.0,
                       help="Min experimental frequency (default: 200.0)")
    parser.add_argument("--exp_max_mhz", type=float, default=400.0,
                       help="Max experimental frequency (default: 400.0)")
    
    # Need to reconstruct K/D/G grid used in original calculation
    parser.add_argument("--c11_base_gpa", type=float, default=229.0,
                       help="Base C11 in GPa (default: 229.0)")
    parser.add_argument("--c12_base_gpa", type=float, default=119.0,
                       help="Base C12 in GPa (default: 119.0)")
    parser.add_argument("--c44_base_gpa", type=float, default=43.0,
                       help="Base C44 in GPa (default: 43.0)")
    parser.add_argument("--res", type=int, default=30,
                       help="Grid resolution used in original run (default: 30)")
    parser.add_argument("--plot_kdg", action="store_true",
                       help="Original run used K/D/G axes")
    
    args = parser.parse_args()
    
    print("="*70)
    print("TOP KS COMBINATIONS ANALYSIS")
    print("="*70)
    
    # Load cache (now contains K/D/G directly!)
    print(f"\n1. Loading KS cache from: {args.cache_file}")
    cache_entries = load_ks_cache(args.cache_file)
    
    # Sort by KS (ascending - lowest = best)
    valid_entries = [e for e in cache_entries if 'KS' in e and np.isfinite(e['KS'])]
    valid_entries.sort(key=lambda x: x['KS'])
    
    if len(valid_entries) == 0:
        raise RuntimeError("No valid KS entries found in cache!")
    
    top_entries = valid_entries[:args.top_n]
    
    print(f"   Found {len(valid_entries)} valid entries in cache")
    print(f"\n   Top {args.top_n} K/D/G combinations:")
    for i, entry in enumerate(top_entries, 1):
        print(f"   #{i}: K={entry['K']:.1f}, D={entry['D']:.1f}, G={entry['G']:.1f} GPa → KS={entry['KS']:.6f}")
    
    # Load EBSD map
    print(f"\n2. Loading EBSD map from: {args.ebsd_path}")
    ebsd_map = load_ebsd_map(
        args.ebsd_path,
        "OxfordText",
        5.0,  # boundary_def_deg
        10    # min_grain_px
    )
    if not ebsd_map:
        raise RuntimeError(f"Failed to load EBSD map from {args.ebsd_path}")
    print(f"   Loaded {len(ebsd_map.grainList)} grains")
    
    # Load experimental data
    print(f"\n3. Loading experimental data from: {args.experimental_h5}")
    exp_mhz = load_experimental_freqs_mhz(
        args.experimental_h5,
        args.exp_min_mhz,
        args.exp_max_mhz
    )
    if exp_mhz.size == 0:
        raise RuntimeError("No experimental frequencies loaded")
    print(f"   Loaded {exp_mhz.size} experimental measurements")
    
    wavelength_m = args.wavelength_um * 1e-6
    
    # Compute frequency distributions for top N using ANY sampling you want!
    print(f"\n4. Computing SAW frequency distributions for top {args.top_n}...")
    print(f"   Using sampling={args.sampling} (can be different from original cache)")
    
